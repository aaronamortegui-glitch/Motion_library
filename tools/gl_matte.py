"""gl-transitions (MIT/BSD shaders, tools/gl_transitions/gl-transitions.json 2.0.0) as luma mattes for After Effects.

A transition shader is rendered from black (the outgoing clip) to white (the incoming one), so each frame is the mix
between them. Placed as the incoming layer's luma track matte, it plays that transition between any two layers
(MCP gl_transition). Shaders that bend or recolour the images themselves (warps, glitches, colour fades) only keep
their shape: the list marks the ones whose matte is a clean pattern (`kind`).

Usage:
  python tools/gl_matte.py list                                        name, kind, tags
  python tools/gl_matte.py render <name> [--w 1920 --h 1080 --fps 30 --dur 0.8 --ease Cruise] [out.mov]
  python tools/gl_matte.py survey                                      classify every shader (writes library/gl_transitions.json)
Mattes are cached in renders/gl_mattes/ (git-ignored).
"""
import argparse, base64, io, json, os, subprocess, sys
import numpy as np
from PIL import Image
from playwright.sync_api import sync_playwright

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
EXCLUDE = {"LeafWipe": "the shape is a cannabis leaf: not for brand work"}   # never offered, whatever the survey says
HOST = os.path.join(HERE, "gl_transitions", "matte.html")
CACHE = os.path.join(ROOT, "renders", "gl_mattes")


def _page(p):
    sys.path.insert(0, HERE); from sound_kit import browser, url
    b = browser(p, "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"); pg = b.new_page()
    pg.goto(url(HOST, "")); pg.wait_for_function("typeof window.MATTE === 'function'", timeout=30000); return b, pg


def _ease(name):
    toks = {e["name"]: e["bezier"] for e in json.load(open(os.path.join(ROOT, "tokens", "superside_motion_tokens.json"), encoding="utf-8"))["easings"]}
    x1, y1, x2, y2 = toks.get(name, toks["Cruise"])
    def f(x):
        lo, hi = 0.0, 1.0
        for _ in range(40):
            t = (lo + hi) / 2; bx = 3 * (1 - t) ** 2 * t * x1 + 3 * (1 - t) * t * t * x2 + t ** 3
            lo, hi = (t, hi) if bx < x else (lo, t)
        t = (lo + hi) / 2; return 3 * (1 - t) ** 2 * t * y1 + 3 * (1 - t) * t * t * y2 + t ** 3
    return f


def render(name, w=1920, h=1080, fps=30, dur=0.8, ease="Cruise", out=None):
    n = max(2, round(dur * fps)); f = _ease(ease); prog = [f(i / (n - 1)) for i in range(n)]
    os.makedirs(CACHE, exist_ok=True)
    out = out or os.path.join(CACHE, f"{name}_{w}x{h}_{fps:g}fps_{dur:g}s_{ease}.mov")
    if os.path.exists(out): return out
    with sync_playwright() as p:
        b, pg = _page(p); urls = pg.evaluate("a => MATTE(a[0], a[1], a[2], a[3])", [name, w, h, prog]); b.close()
    ff = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "image2pipe", "-framerate", str(fps), "-i", "-", "-vf", "format=gray",
                           "-c:v", "prores_ks", "-profile:v", "3", "-pix_fmt", "yuv422p10le", out], stdin=subprocess.PIPE)
    for u in urls: ff.stdin.write(base64.b64decode(u.split(",", 1)[1]))
    ff.stdin.close(); ff.wait()
    return out


def survey():
    """Renders each shader small at 5 progresses and sorts it: wipe (a hard edge between black and white), soft (a
    pattern with greys), fade (flat grey: a plain dissolve), needs_images (draws something that is not the mix)."""
    with sync_playwright() as p:
        b, pg = _page(p); items = pg.evaluate("LIST()"); out = []
        for it in items:
            if it["name"] in EXCLUDE: out.append({**it, "kind": "excluded", "why": EXCLUDE[it["name"]]}); continue
            if it["textures"]: out.append({**it, "kind": "needs_textures"}); continue
            try: urls = pg.evaluate("a => MATTE(a[0], 192, 108, [0.2, 0.35, 0.5, 0.65, 0.8])", [it["name"]])
            except Exception as e: out.append({**it, "kind": "error", "error": str(e)[:120]}); continue
            fr = [np.asarray(Image.open(io.BytesIO(base64.b64decode(u.split(",", 1)[1]))).convert("RGB"), dtype=np.float32) / 255 for u in urls]
            chroma = max(float(np.abs(a - a.mean(2, keepdims=True)).max()) for a in fr)
            spread = max(float(a.std()) for a in fr); mid = [float(((a > .1) & (a < .9)).mean()) for a in fr]
            means = [float(a.mean()) for a in fr]; mono = all(x <= y + 0.02 for x, y in zip(means, means[1:]))
            kind = "needs_images" if chroma > 0.08 or not mono else "fade" if spread < 0.02 else "wipe" if max(mid) < 0.08 else "soft"
            out.append({**it, "kind": kind, "coverage": [round(m, 3) for m in means]})
        b.close()
    data = {"source": "https://github.com/gl-transitions/gl-transitions", "version": "2.0.0", "license": "MIT / BSD per shader (field license)",
            "note": "Generated by tools/gl_matte.py survey. kind wipe/soft = a clean luma matte (MCP gl_transition); fade = a plain dissolve; "
                    "needs_images/needs_textures = the shader changes the pictures themselves, so as a matte only its shape survives.",
            "transitions": [{k: v for k, v in x.items() if k != "textures"} for x in out]}
    json.dump(data, open(os.path.join(ROOT, "library", "gl_transitions.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    from collections import Counter; print(Counter(x["kind"] for x in out))


if __name__ == "__main__":
    a = argparse.ArgumentParser(); a.add_argument("cmd"); a.add_argument("name", nargs="?"); a.add_argument("out", nargs="?")
    a.add_argument("--w", type=int, default=1920); a.add_argument("--h", type=int, default=1080); a.add_argument("--fps", type=float, default=30)
    a.add_argument("--dur", type=float, default=0.8); a.add_argument("--ease", default="Cruise"); x = a.parse_args()
    if x.cmd == "survey": survey()
    elif x.cmd == "render": print(render(x.name, x.w, x.h, x.fps, x.dur, x.ease, x.out))
    else:
        for t in json.load(open(os.path.join(ROOT, "library", "gl_transitions.json"), encoding="utf-8"))["transitions"]: print(f"{t['name']:<28} {t['kind']:<15} {', '.join(t.get('tags') or [])}")
