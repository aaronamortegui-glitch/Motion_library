"""Motion DNA bridge to HyperFrames (heygen-com/hyperframes, Apache-2.0, pinned to 0.8.203 in package.json).

HyperFrames turns HTML + seekable animation (GSAP, CSS, Lottie, three.js, anime.js) into deterministic MP4, and ships a
registry of ~450 blocks and components (transitions, titles, captions, charts, 3D, mock UI). This bridge makes every
project speak Motion DNA: our colours and fonts on HyperFrames' token contract (--bg, --fg, --brand, --accent...), our
14 token curves registered as GSAP eases ("mdna.Land", "mdna.Pop"...), our durations, and our Tone.js sound kit (tools/sound_kit.py).

Usage (from the repo root; telemetry is always off):
  python research/hyperframes/hf.py new <name> [--res landscape|portrait|square]   project in research/hyperframes/projects/
  python research/hyperframes/hf.py add <name> <registry-item>                        install a block or component
  python research/hyperframes/hf.py render <name> [--sound track.json] [--draft]      MP4 in the project's renders/
  python research/hyperframes/hf.py find <words...>                                   search catalog.json (offline)
  python research/hyperframes/hf.py catalog                                           refresh catalog.json from the registry
Needs: node 18+ (npm install once in research/hyperframes), ffmpeg, Chrome. Projects are git-ignored.
"""
import json, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PROJECTS = os.path.join(HERE, "projects")
VERSION = "0.8.203"
ENV = {**os.environ, "DO_NOT_TRACK": "1", "HYPERFRAMES_NO_TELEMETRY": "1", "HYPERFRAMES_SKIP_SKILLS": "1"}
COLORS = {"pine": "#0A211F", "spark": "#D8FF85", "cloud": "#F7F9F2", "sea": "#174A46", "ink": "#04120F", "mint": "#9FD8C2", "coral": "#FF8A6B", "sky": "#7FB8FF"}

# HyperFrames components paint only from these contract tokens, so mapping them once restyles the whole registry
CONTRACT = {"--bg": "pine", "--bg-2": "ink", "--surface": "sea", "--fg": "cloud", "--muted": "mint", "--border": "sea",
            "--border-dark": "ink", "--brand": "spark", "--accent": "spark", "--accent-light": "mint", "--accent-2": "coral"}

# registry sound ids (hf:sfx events) -> our kit (tools/sound/mdna_audio.js); anything unknown falls back by keyword
SFX_MAP = {"whip-cut": "whoosh", "cut": "swish", "hit": "hit", "impact": "hit", "pop": "pop", "click": "click", "tick": "tick",
           "type": "type", "reveal": "shimmer", "land": "pop", "success": "chime", "glitch": "glitch", "rise": "riser"}


def npx(*args, cwd=HERE, capture=False):
    cmd = ["npx", "--no-install", "hyperframes", *args]
    if os.name == "nt": cmd = ["cmd", "/c", *cmd]
    return subprocess.run(cmd, cwd=cwd, env=ENV, check=True, text=True, capture_output=capture, encoding="utf-8")


def tokens():
    return json.load(open(os.path.join(ROOT, "tokens", "superside_motion_tokens.json"), encoding="utf-8"))


def kit_files(dst):
    """Writes mdna/ into a project: mdna.css (fonts + contract tokens), mdna-gsap.js (curves + durations), the fonts."""
    t = tokens(); os.makedirs(os.path.join(dst, "fonts"), exist_ok=True)
    for f in ("InterTight[wght].ttf", "InstrumentSerif-Regular.ttf", "InstrumentSerif-Italic.ttf", "OFL-InterTight.txt", "OFL-InstrumentSerif.txt"):
        shutil.copy2(os.path.join(ROOT, "assets", "fonts", f), os.path.join(dst, "fonts", f))
    css = ["/* Motion DNA tokens for HyperFrames. Generated by research/hyperframes/hf.py from tokens/superside_motion_tokens.json. */",
           "@font-face { font-family: 'Inter Tight'; src: url('fonts/InterTight[wght].ttf') format('truetype'); font-weight: 100 900; }",
           "@font-face { font-family: 'Instrument Serif'; src: url('fonts/InstrumentSerif-Regular.ttf') format('truetype'); }",
           "@font-face { font-family: 'Instrument Serif'; font-style: italic; src: url('fonts/InstrumentSerif-Italic.ttf') format('truetype'); }",
           ":root {"]
    css += [f"  --mdna-{k}: {v};" for k, v in COLORS.items()]
    css += [f"  {k}: var(--mdna-{v});" for k, v in CONTRACT.items()]
    css += ["  --ground: var(--mdna-pine); --ink: var(--mdna-cloud);",
            "  --font-display: 'Instrument Serif', Georgia, serif; --font-body: 'Inter Tight', Arial, sans-serif; --font-mono: ui-monospace, Consolas, monospace;",
            "  --radius: 14px; --radius-sm: 8px; --radius-md: 14px; --radius-lg: 22px; --radius-xl: 32px; --radius-button: 999px;"]
    css += [f"  --dur-{d['name'].lower()}: {d['ms']}ms;" for d in t["durations"]]
    css += [f"  --ease-{e['name'].lower()}: cubic-bezier({', '.join(str(x) for x in e['bezier'])});" for e in t["easings"]]
    css += ["}"]
    open(os.path.join(dst, "mdna.css"), "w", encoding="utf-8").write("\n".join(css) + "\n")
    eases = {e["name"]: e["bezier"] for e in t["easings"]}
    durs = {d["name"]: round(d["ms"] / 1000, 3) for d in t["durations"]}
    js = f"""// Motion DNA curves and durations for GSAP in HyperFrames. Generated by research/hyperframes/hf.py from the token file.
// Use them by name:  tl.to(el, {{ y: 0, duration: MDNA.dur.Arrive, ease: "mdna.Land" }})
(function () {{
  const EASES = {json.dumps(eases)}, DUR = {json.dumps(durs)};
  function bezier(x1, y1, x2, y2) {{
    const A = (a, b) => 1 - 3 * b + 3 * a, B = (a, b) => 3 * b - 6 * a, C = a => 3 * a;
    const f = (t, a, b) => ((A(a, b) * t + B(a, b)) * t + C(a)) * t, d = (t, a, b) => 3 * A(a, b) * t * t + 2 * B(a, b) * t + C(a);
    return x => {{
      if (x <= 0) return 0; if (x >= 1) return 1;
      let t = x; for (let i = 0; i < 8; i++) {{ const s = d(t, x1, x2); if (Math.abs(s) < 1e-6) break; t -= (f(t, x1, x2) - x) / s; }}
      if (t < 0 || t > 1) {{ let lo = 0, hi = 1; t = x; for (let i = 0; i < 30; i++) {{ const v = f(t, x1, x2); if (v < x) lo = t; else hi = t; t = (lo + hi) / 2; }} }}
      return f(t, y1, y2);
    }};
  }}
  const ease = {{}};
  for (const k in EASES) {{ ease[k] = bezier(...EASES[k]); if (window.gsap) gsap.registerEase("mdna." + k, ease[k]); }}
  window.MDNA = Object.assign(window.MDNA || {{}}, {{ ease, dur: DUR, curves: EASES }});
}})();
"""
    open(os.path.join(dst, "mdna-gsap.js"), "w", encoding="utf-8").write(js)


def new(name, res="landscape"):
    os.makedirs(PROJECTS, exist_ok=True); proj = os.path.join(PROJECTS, name)
    if os.path.exists(proj): sys.exit(f"{proj} exists")
    npx("init", name, "--example", "blank", "--non-interactive", "--skip-transcribe", "--resolution", res, cwd=PROJECTS)
    kit_files(os.path.join(proj, "mdna"))
    idx = os.path.join(proj, "index.html"); h = open(idx, encoding="utf-8").read()
    h = re.sub(r"(<script src=\"[^\"]*gsap[^\"]*\"></script>)", r'\1\n    <link rel="stylesheet" href="mdna/mdna.css" />\n    <script src="mdna/mdna-gsap.js"></script>', h, count=1)
    h = re.sub(r"\s*/\* Placeholders:.*?\*/\s*:root \{.*?\}", "", h, count=1, flags=re.S)   # the tokens now come from mdna.css
    open(idx, "w", encoding="utf-8").write(h)
    print(json.dumps({"project": proj, "kit": "mdna/ (mdna.css, mdna-gsap.js, fonts)"}))


def add(name, item): npx("add", item, cwd=os.path.join(PROJECTS, name))


def render(name, sound=None, draft=False):
    proj = os.path.join(PROJECTS, name); os.makedirs(os.path.join(proj, "renders"), exist_ok=True)
    out = os.path.join(proj, "renders", name + ".mp4")
    npx("render", "-o", out, "-q", "draft" if draft else "looks", cwd=proj)
    if sound:   # lay a Motion DNA sound track under it (same mixer as the code templates)
        sys.path.insert(0, os.path.join(ROOT, "tools")); import sound_kit
        wav = sound_kit.render(json.load(open(sound, encoding="utf-8")), os.path.splitext(out)[0] + ".wav", True)
        out = sound_kit.mux(out, wav, True)
    print(json.dumps({"render": out}))


def catalog():
    raw = json.loads(npx("catalog", "--json", capture=True).stdout)
    fam = [("transition", "transition"), ("caption", "captions"), ("typography", "text"), ("text", "text"), ("lower-third", "text"),
           ("title-card", "text"), ("background", "background"), ("texture", "look"), ("shader", "look"), ("overlay", "overlay"),
           ("3d", "3d"), ("data", "data"), ("chart", "data"), ("mock-ui", "ui"), ("ui-props", "ui"), ("cursor", "ui"), ("camera", "camera"),
           ("carousel", "showcase"), ("gallery", "showcase"), ("showcase", "showcase"), ("social", "social"), ("motion-primitive", "move")]
    items = [{**i, "family": next((f for tag, f in fam if tag in i.get("tags", [])), "other")} for i in raw]
    out = {"source": "https://github.com/heygen-com/hyperframes registry", "version": VERSION, "license": "Apache-2.0",
           "note": "Index for search only: install with hf.py add, which copies the item's source into a project.", "items": items}
    json.dump(out, open(os.path.join(HERE, "catalog.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print(json.dumps({"items": len(items)}))


def find(words):
    items = json.load(open(os.path.join(HERE, "catalog.json"), encoding="utf-8"))["items"]
    ws = [w.lower() for w in words]
    score = lambda i: sum(3 * (w in i["name"]) + 2 * (w in " ".join(i.get("tags", []))) + (w in i.get("description", "").lower()) for w in ws)
    for i in sorted((i for i in items if score(i)), key=score, reverse=True)[:15]:
        print(f"{i['name']:<32} {i['type']:<10} {i['family']:<11} {i.get('description', '')[:90]}")


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a: sys.exit(__doc__)
    cmd = a[0]
    if cmd == "new": new(a[1], a[a.index("--res") + 1] if "--res" in a else "landscape")
    elif cmd == "add": add(a[1], a[2])
    elif cmd == "render": render(a[1], a[a.index("--sound") + 1] if "--sound" in a else None, "--draft" in a)
    elif cmd == "find": find(a[1:])
    elif cmd == "catalog": catalog()
    else: sys.exit(__doc__)
